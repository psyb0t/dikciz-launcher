"""Publish the packaged MCP recipes as browser-readable documentation."""

import argparse
import importlib.util
import json
import logging
from pathlib import Path
import re
from string import Template

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "app/src/dikciz/assets/mcp/recipes"
OUTPUT = ROOT / "docs"
LOGGER = logging.getLogger(__name__)
GUIDES = {
    "native-data": "native-device-control",
    "html": "javascript-api",
    "permissions": "android-access",
    "files": "files-and-apks",
    "lua": "lua-api",
    "apps": "remote-device-control",
    "ui": "automation-control",
    "connect": "automation-control",
    "discovery": "automation-control",
    "shell": "shell-sessions",
}
DESCRIPTIONS = {
    "contact-sms": "Find a contact's exact phone number, send one tracked SMS with an idempotency key and inspect the receipt without navigating another app.",
    "event-lua": "Use the complete Lua receiver for a two-event example that persists running state and emits a custom event for its HTML widget.",
    "event-setup": "Install and verify a two-input custom-event pipeline that updates saved Lua state and a visible HTML widget with explicit acknowledgements.",
    "event-widget": "Use the complete HTML receiver for a Lua event pipeline, including bridge readiness, saved state and rendered-text acknowledgement.",
    "html-item": "Inspect, edit or remove one saved HTML item inside its WebView without replacing the surrounding document or another widget.",
    "inspect-ui": "Inspect semantic UI state, choose stable element IDs, trigger an action and verify the resulting screen before continuing.",
    "install-apk": "Upload an APK, request Android installation, inspect owner-confirmation state and verify that the intended package was installed.",
    "install-script": "Install a Lua script with its policy and event subscriptions while preserving existing phone configuration and checking execution results.",
    "install-widget": "Add an HTML widget through the shared APIs, preserve page configuration and verify its address, bridge readiness and saved state.",
    "launch-app": "Discover an Android app, launch its exact package or activity and inspect the observed foreground result instead of assuming success.",
    "listener": "Change the phone listener address and ports, reconnect at the intended private endpoint and verify the actual reported binding.",
    "restart": "Restart Dikciz or hand control to a replacement package, then rediscover the listener and verify the running application version.",
    "stream-logs": "Read continuous log output with retained shell sessions, reconnect after interruptions and stop the stream when inspection is complete.",
    "travel-todo": "Operate the bundled Travel todo example, configure a GPS arrival and verify task state and custom-event handling without messaging anyone.",
}
PAGE = Template("""---
title: $title
description: $description
permalink: /recipe-$slug/
parent: Recipes
nav_order: $order
---

<!-- Generated by make docs-recipes from the packaged MCP recipe. -->

<!-- {% raw %} -->
$body
<!-- {% endraw %} -->
""")


def browser_link(match):
    section, slug = match.group(1).split("/", 1)
    if section == "recipes":
        if slug not in DESCRIPTIONS:
            raise ValueError("Unknown recipe link: " + slug)
        return "recipe-" + slug + ".md"
    if section != "guides" or slug not in GUIDES:
        raise ValueError("Unknown guide link: " + slug)
    return GUIDES[slug] + ".md"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check", action="store_true", help="Reject stale website recipes"
    )
    args = parser.parse_args()
    spec = importlib.util.spec_from_file_location(
        "site_recipe_logging", ROOT / "scripts/dikciz-control.py"
    )
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    module.configure_logging(ROOT / ".testing/site-recipes-generation.log")
    try:
        paths = sorted(SOURCE.glob("*.md"))
        if {path.stem for path in paths} != set(DESCRIPTIONS):
            raise ValueError("Recipe metadata must cover every packaged recipe")
        for order, path in enumerate(paths, 1):
            body = path.read_text()
            title = next(
                line[2:] for line in body.splitlines() if line.startswith("# ")
            )
            body = re.sub(r"dikciz://docs/([a-z-]+/[a-z-]+)", browser_link, body)
            text = PAGE.substitute(
                title=json.dumps(title),
                description=json.dumps(DESCRIPTIONS[path.stem]),
                slug=path.stem,
                order=order,
                body=body.rstrip(),
            )
            output = OUTPUT / ("recipe-" + path.name)
            if args.check:
                if not output.exists() or output.read_text() != text:
                    raise ValueError("Website recipe is stale: " + path.name)
                continue
            output.write_text(text)
        LOGGER.info("Website recipes verified", extra={"recipe_count": len(paths)})
    except (OSError, ValueError, KeyError, StopIteration):
        LOGGER.exception("Website recipe generation failed")
        raise


if __name__ == "__main__":
    main()
